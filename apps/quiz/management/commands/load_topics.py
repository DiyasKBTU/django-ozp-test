class Command(BaseCommand):
    help = "11 тақырып пен 20 тақырыпшаны (қаз/орыс) жүктейді"

    @transaction.atomic
    def handle(self, *args, **options):
        topic_count = 0
        subtopic_count = 0

        for topic_number, topic_kk, topic_ru, subtopics in TOPICS:
            topic, _ = Topic.objects.update_or_create(
                number=topic_number,
                defaults={"name_kk": topic_kk, "name_ru": topic_ru},
            )
            topic_count += 1

            for subtopic_number, subtopic_kk, subtopic_ru in subtopics:
                Subtopic.objects.update_or_create(
                    number=subtopic_number,
                    defaults={
                        "topic": topic,
                        "name_kk": subtopic_kk,
                        "name_ru": subtopic_ru,
                    },
                )
                subtopic_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Жүктелді: {topic_count} тақырып, {subtopic_count} тақырыпша."
            )
        )
